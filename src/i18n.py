def system_lang() -> str:
    """Detect OS language, mapped to supported codes (fallback: en)."""
    try:
        import locale

        loc = (locale.getdefaultlocale()[0] or "").lower()
        prefix = loc.split("_")[0]
        return LOCALE_MAP.get(prefix, DEFAULT_LANG)
    except Exception:
        return DEFAULT_LANG


